"""PyTorch Dataset for KITTI 3D object detection using EXP-002 manifest."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

import json
import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset

from src.config import load_config
from src.data.calibration import parse_calibration_file
from src.data.kitti_parser import parse_label_file
from src.data.target_encoder import build_class_mapping, encode_annotations, EncodedTarget
from src.data.transforms import (
    ImageTransform,
    PreprocessingMode,
    make_image_transform,
    preprocess_image,
)


@dataclass(frozen=True)
class KittiSample:
    """A single sample from the KITTI dataset.

    Attributes:
        frame_id: KITTI frame identifier (e.g., "000000").
        image: Preprocessed image tensor [C, H, W] in RGB order, float32 in [0, 1].
        target: EncodedTarget with class_ids, bboxes_2d, dimensions_3d, locations_3d, rotation_y.
        original_image_size: (width, height) of the original image.
        calibration: Parsed calibration (optional, for advanced use).
    """

    frame_id: str
    image: torch.Tensor
    target: EncodedTarget
    original_image_size: tuple[int, int]
    calibration: dict[str, np.ndarray] | None = None


class KittiManifestDataset(Dataset[KittiSample]):
    """KITTI 3D Object Detection Dataset driven by an EXP-002 manifest.

    This dataset reads the manifest generated by EXP-002 preparation and
    loads frames on demand. It applies the declared preprocessing transform
    and encodes annotations using the target encoder.

    The manifest contains:
    - Preprocessing parameters (mode, scale, padding)
    - Transformed P2 matrix per frame
    - Train/validation split
    - Per-frame paths and metadata

    Args:
        manifest_path: Path to the EXP-002 manifest JSON.
        dataset_root: Root directory of the KITTI dataset (where image_2/,
            label_2/, calib/ live). Paths in manifest are relative to this.
        split: "train" or "validation".
        class_mapping: Optional list of class names defining the class->index
            mapping. If None, the manifest's observed classes are used.
        expected_channels: Expected number of image channels (default 3).
    """

    def __init__(
        self,
        manifest_path: str | Path,
        dataset_root: str | Path,
        split: Literal["train", "validation"],
        class_mapping: list[str] | None = None,
        expected_channels: int = 3,
    ) -> None:
        self.manifest_path = Path(manifest_path)
        self.dataset_root = Path(dataset_root)
        self.split = split
        self.expected_channels = expected_channels

        with self.manifest_path.open("r", encoding="utf-8") as f:
            manifest = json.load(f)

        if manifest.get("format") != "kitti-preparation-manifest-v1":
            raise ValueError(f"Unsupported manifest format: {manifest.get('format')}")

        self.preprocessing_mode: PreprocessingMode = manifest["preprocessing_mode"]
        self.output_image_size = (
            manifest["output_image_size"]["width"],
            manifest["output_image_size"]["height"],
        )

        # Filter frames by split
        self.frames = [
            frame for frame in manifest["frames"]
            if frame["split"] == split
        ]

        if not self.frames:
            raise ValueError(f"No frames found for split '{split}' in manifest")

        # Build class mapping
        all_observed = set()
        for frame in manifest["frames"]:
            # We don't have per-frame class info in manifest, so we'll parse labels
            # For now, build from configuration or use a default
            pass

        # We'll build the class mapping lazily from the first batch of annotations
        # For now, use provided mapping or fall back to config default
        self.class_mapping = class_mapping
        self._class_to_idx: dict[str, int] | None = None
        self._idx_to_class: list[str] | None = None

    def _ensure_class_mapping(self) -> tuple[dict[str, int], list[str]]:
        """Build class mapping from configuration or manifest."""
        if self._class_to_idx is not None:
            return self._class_to_idx, self._idx_to_class

        # Load config to get class mapping
        config = load_config()
        configured_classes = config.get("dataset", {}).get("classes")

        if self.class_mapping is not None:
            # Use provided mapping
            class_to_idx = {name: idx for idx, name in enumerate(self.class_mapping)}
            idx_to_class = list(self.class_mapping)
        elif configured_classes is not None:
            # Use config
            class_to_idx = {name: idx for idx, name in enumerate(configured_classes)}
            idx_to_class = list(configured_classes)
        else:
            # We need to discover classes by parsing all label files
            # This is expensive, so we do it once
            observed = set()
            for frame in self.frames:
                label_path = self.dataset_root / frame["label_path"]
                try:
                    annotations = parse_label_file(label_path)
                    for ann in annotations:
                        if not ann.is_dontcare:
                            observed.add(ann.class_name)
                except Exception:
                    pass
            class_list = sorted(observed)
            class_to_idx = {name: idx for idx, name in enumerate(class_list)}
            idx_to_class = class_list

        self._class_to_idx = class_to_idx
        self._idx_to_class = idx_to_class
        return class_to_idx, idx_to_class

    def __len__(self) -> int:
        return len(self.frames)

    def __getitem__(self, idx: int) -> KittiSample:
        frame = self.frames[idx]
        frame_id = frame["frame_id"]

        # Load and preprocess image
        image_path = self.dataset_root / frame["image_path"]
        with Image.open(image_path) as img:
            img.load()
            if img.mode != "RGB":
                img = img.convert("RGB")
            orig_width, orig_height = img.size

            # Create transform from manifest
            prep = frame["preprocessing"]
            transform = ImageTransform(
                mode=prep["mode"],
                original_width=prep["original_width"],
                original_height=prep["original_height"],
                output_width=prep["output_width"],
                output_height=prep["output_height"],
                resized_width=prep["resized_width"],
                resized_height=prep["resized_height"],
                scale_x=prep["scale_x"],
                scale_y=prep["scale_y"],
                pad_x=prep["pad_x"],
                pad_y=prep["pad_y"],
                pad_right=prep["pad_right"],
                pad_bottom=prep["pad_bottom"],
            )

            # Apply preprocessing
            processed_img = preprocess_image(img, transform, padding_value=114)

        # Convert to tensor [C, H, W], float32, [0, 1]
        img_array = np.array(processed_img, dtype=np.float32) / 255.0
        img_tensor = torch.from_numpy(img_array).permute(2, 0, 1).contiguous()

        # Load and parse annotations
        label_path = self.dataset_root / frame["label_path"]
        annotations = parse_label_file(label_path)

        # Load calibration for transformed P2
        calib_path = self.dataset_root / frame["calibration_path"]
        calibration = parse_calibration_file(calib_path)
        transformed_p2 = np.array(frame["transformed_p2"], dtype=np.float64)

        # Ensure class mapping is built
        class_to_idx, _ = self._ensure_class_mapping()

        # Encode annotations
        target = encode_annotations(
            annotations,
            class_to_idx,
            self.output_image_size,
            transformed_p2,
        )

        # Prepare calibration dict (optional, for advanced use)
        calib_dict = {k: v.astype(np.float32) for k, v in calibration.matrices.items()}

        return KittiSample(
            frame_id=frame_id,
            image=img_tensor,
            target=target,
            original_image_size=(orig_width, orig_height),
            calibration=calib_dict,
        )

    @property
    def class_to_idx(self) -> dict[str, int]:
        """Get the class name to index mapping."""
        self._ensure_class_mapping()
        assert self._class_to_idx is not None
        return self._class_to_idx

    @property
    def idx_to_class(self) -> list[str]:
        """Get the index to class name mapping."""
        self._ensure_class_mapping()
        assert self._idx_to_class is not None
        return self._idx_to_class

    @property
    def num_classes(self) -> int:
        """Get the number of classes."""
        return len(self.idx_to_class)


def kitti_collate_fn(batch: list[KittiSample]) -> dict[str, Any]:
    """Collate function for KittiManifestDataset.

    Handles variable number of objects per frame by returning lists
    for object-level targets and stacked tensors for images.

    Returns:
        Dict with:
            - "images": Tensor [B, C, H, W]
            - "targets": List[EncodedTarget] of length B
            - "frame_ids": List[str] of length B
            - "original_sizes": List[tuple[int, int]] of length B
            - "calibrations": List[dict] of length B
    """
    images = torch.stack([sample.image for sample in batch], dim=0)
    targets = [sample.target for sample in batch]
    frame_ids = [sample.frame_id for sample in batch]
    original_sizes = [sample.original_image_size for sample in batch]
    calibrations = [sample.calibration for sample in batch]

    return {
        "images": images,
        "targets": targets,
        "frame_ids": frame_ids,
        "original_sizes": original_sizes,
        "calibrations": calibrations,
    }